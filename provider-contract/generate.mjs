// Preserve handwritten implementations/defaults while keeping their method KDoc in sync.
function documentKotlinMethods(path) {
  const source = readFileSync(resolve(root, path), "utf8").replaceAll("\r\n", "\n");
  return source.replace(/(?:    \/\*\* (?:(?!\*\/)[^\n])*\*\/\n)?    suspend fun (\w+)\(request: (\w+)\): (\w+)/g,
    (declaration, name, request, response) => {
      const op = schema.operations[name];
      if (!op?.capability) return declaration;
      if (op.request !== request || op.response !== response)
        throw Error(`Kotlin declaration differs from schema: ${path}:${name}`);
      return comment(operationDescription(name, op), "    ") +
        `    suspend fun ${name}(request: ${request}): ${response}`;
    });
}
