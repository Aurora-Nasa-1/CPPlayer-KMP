function wireEncode(type, value, out) {
  if (type.endsWith("?")) {
    if (value === null || value === undefined) {
      out.push(0);
      return;
    }
    out.push(1);
    wireEncode(type.slice(0, -1), value, out);
    return;
  }
  if (type.endsWith("[]")) {
    int32(out, value.length);
    for (const item of value) wireEncode(type.slice(0, -2), item, out);
    return;
  }
  if (type === "string") return rawBytes(out, Buffer.from(value, "utf8"));
  if (type === "bytes") return rawBytes(out, Buffer.from(value));
  if (type === "bool") return out.push(value ? 1 : 0);
  if (type === "int") return int32(out, value);
  if (type === "long") {
    const buffer = Buffer.alloc(8);
    buffer.writeBigInt64LE(BigInt(value));
    out.push(...buffer);
    return;
  }
  const record = schema.records[type];
  if (!record) throw new Error(`Unknown vector type ${type}`);
  for (const [field, fieldType] of Object.entries(record)) wireEncode(fieldType, value[field], out);
}

function int32(out, value) {
  const buffer = Buffer.alloc(4);
  buffer.writeInt32LE(value);
  out.push(...buffer);
}

function rawBytes(out, buffer) {
  int32(out, buffer.length);
  out.push(...buffer);
}

