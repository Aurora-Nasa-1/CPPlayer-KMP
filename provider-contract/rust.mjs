// `Option<Self>` inside a record needs indirection in Rust; `Vec<Self>` does not.
// Build the graph of non-list record references and mark every field that can
// reach its own record again as boxed.
const records = new Set(Object.keys(schema.records));
const edges = new Map([...records].map(name => [name, []]));
for (const [name, fields] of Object.entries(schema.records)) {
  for (const type of Object.values(fields)) {
    const inner = type.endsWith("?") ? type.slice(0, -1) : null;
    if (inner && records.has(inner) && inner !== name) edges.get(name).push(inner);
    if (inner === name) edges.get(name).push(inner);
  }
}
const reachesSelf = name => {
  const seen = new Set();
  const stack = [...edges.get(name)];
  while (stack.length) {
    const next = stack.pop();
    if (next === name) return true;
    if (seen.has(next)) continue;
    seen.add(next);
    stack.push(...(edges.get(next) ?? []));
  }
  return false;
};
const boxed = new Set();
for (const name of records) {
  if (!reachesSelf(name)) continue;
  for (const [field, type] of Object.entries(schema.records[name])) {
    if (type === `${name}?`) boxed.add(`${name}.${field}`);
  }
}

function rustType(type, key = "") {
  if (boxed.has(key)) return `Option<Box<${rustType(type.slice(0, -1))}>>`;
  if (type.endsWith("?")) return `Option<${rustType(type.slice(0, -1))}>`;
  if (type.endsWith("[]")) return `Vec<${rustType(type.slice(0, -2))}>`;
  switch (type) {
    case "string": return "String";
    case "int": return "i32";
    case "long": return "i64";
    case "bool": return "bool";
    case "bytes": return "Vec<u8>";
    default: return rustRecord(type);
  }
}

// `Call` expressions return `Result<(), WireError>` / `Result<T, WireError>` so
// the caller only adds `?`. Keeping them composable is what makes nested
// lists and optional records correct without special cases.
// `target` is a reference expression (`&value` or `value` inside a closure).
function writeCall(type, target) {
  if (type === "string") return `w.string(${target})`;
  if (type === "bytes") return `w.bytes(${target})`;
  if (type === "int" || type === "long" || type === "bool") return `w.${type}(*${target})`;
  if (type.endsWith("[]"))
    return `w.list(${target}, |w, item| ${writeCall(type.slice(0, -2), "item")})`;
  return `(${target}).write(w)`;
}

function readCall(type) {
  if (type === "string") return "r.string()";
  if (type === "bytes") return "r.bytes()";
  if (type === "int" || type === "long" || type === "bool") return `r.${type}()`;
  if (type.endsWith("[]")) return `r.list(|r| ${readCall(type.slice(0, -2))})`;
  return `${rustRecord(type)}::read(r)`;
}

function writeExpr(type, access, key = "") {
  if (type.endsWith("?")) {
    const inner = type.slice(0, -1);
    const boxedField = boxed.has(key);
    const receiver = boxedField || inner === "string" || inner === "bytes" || inner.endsWith("[]")
      ? `${access}.as_deref()`
      : `${access}.as_ref()`;
    return `w.optional(${receiver}, |w, value| ${writeCall(inner, "value")})?;`;
  }
  return `${writeCall(type, `&${access}`)}?;`;
}

function readExpr(type, key = "") {
  if (boxed.has(key)) return `r.optional(|r| ${readCall(type.slice(0, -1))})?.map(Box::new)`;
  if (type.endsWith("?")) return `r.optional(|r| ${readCall(type.slice(0, -1))})?`;
  return `${readCall(type)}?`;
}

